/** The brand gradient, cyan to charcoal, across the logo's width. */
function Gradient({ id }: { id: string }) {
  return (
    <linearGradient id={id} gradientUnits="userSpaceOnUse" x1="259.1" y1="0" x2="673.9" y2="0">
      {STOPS.map(([offset, color]) => (
        <stop key={offset} offset={offset} stopColor={color} />
      ))}
    </linearGradient>
  )
}

/**
 * The Al-Tamkeen logo: the Arabic mark, with ALTAMKEEN under it unless `variant="mark"`.
 * Size it by height (`h-10`). `tone`: gradient on white, charcoal on cyan, cyan on ink, white
 * on the gradient. Without a `title` it is decorative (hidden from screen readers).
 */
export function Logo({
  variant = "full",
  tone = "gradient",
  title,
  className,
  ...props
}: SVGProps<SVGSVGElement> & {
  variant?: "full" | "mark"
  tone?: "gradient" | keyof typeof TONES
  title?: string
}) {
  const id = useId()
  const fill = tone === "gradient" ? `url(#${id})` : TONES[tone]
  return (
    <svg
      viewBox={BOX[variant]}
      className={cn("h-10 w-auto shrink-0", className)}
      {...(title ? { role: "img", "aria-label": title } : { "aria-hidden": true })}
      {...props}
    >
      {tone === "gradient" && (
        <defs>
          <Gradient id={id} />
        </defs>
      )}
      <path fill={fill} d={MARK} />
      {variant === "full" && <path fill={fill} d={WORD} />}
    </svg>
  )
}

/**
 * The loading logo: the mark builds itself piece by piece over its grey silhouette, holds, then
 * lifts away (a 3.6s loop; still under reduced motion). The mark is 1.5 × `size` wide. Leave a
 * quarter of its height free above it, because pieces drop in from there.
 */
export function LoadingLogo({
  label,
  size = 64,
  className,
}: {
  /** Announced to screen readers. */
  label: string
  size?: number
  className?: string
}) {
  const id = useId()
  const width = Math.round(size * 1.5)
  return (
    <div
      role="status"
      aria-live="polite"
      className={cn("inline-flex flex-col items-center", className)}
    >
      <svg viewBox={BOX.mark} width={width} height={width / 2} aria-hidden className="tk-ld">
        <defs>
          <Gradient id={id} />
        </defs>
        <path className="tk-ld-ghost" d={MARK} />
        {PIECES.map((d, i) => (
          <path key={i} className={`tk-ld-p tk-ld-p${i}`} d={d} fill={`url(#${id})`} />
        ))}
      </svg>
      <span className="sr-only">{label}</span>
    </div>
  )
}
